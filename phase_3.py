# ==================== ALEX AGENT ====================

class AlexAgent:

    def __init__(
        self,
        api_key: str,
        rag_system: Optional[RAGSystem] = None,
        model: str = "gemini-3.8-flash"
    ):

        self.api_key = api_key

        self.client = genai.Client(
            api_key=api_key
        )

        self.rag = rag_system

        self.model = model

        self.tools_registry = {}

        self.current_plan = None

        self.execution_history = []

        print(
            "✅ Alex Agent initialized (with RAG)"
        )

        print(
            f"🤖 Model: {self.model}"
        )

    def register_tool(
        self,
        name: str,
        func: callable,
        description: str
    ):

        self.tools_registry[name] = {
            "func": func,
            "description": description,
            "name": name
        }

        print(
            f"📍 Tool: {name}"
        )

    def _log(self, message: str):

        print(
            f"[{datetime.now().strftime('%H:%M:%S')}] "
            f"{message}"
        )

    def _call_gemini(
    self,
    prompt: str,
    temperature: float = 0.7
) -> Optional[str]:

        try:

            response = self.client.models.generate_content(
                model=self.model,
                contents=prompt,
                config={
                    "temperature": temperature
                }
            )

            return response.text

        except Exception as e:

            error_text = str(e)

            # Handle Gemini quota errors gracefully
            if (
                "429" in error_text
                or "RESOURCE_EXHAUSTED" in error_text
                or "quota" in error_text.lower()
            ):

                self._log(
                    "⚠️ Gemini API quota exhausted."
                )

                return None

            # Other errors should still be visible
            self._log(
                f"❌ Gemini Error: {e}"
            )

            raise

# ==================== ADD RAG METHOD TO ALEX ====================

def answer_with_rag(
    self,
    query: str,
    top_k: int = 3
) -> Dict:

    self._log(
        "\n" + "=" * 50
    )

    self._log(
        "🚀 ALEX + RAG"
    )

    self._log(
        "=" * 50
    )

    if not self.rag:

        raise ValueError(
            "RAG system is not connected."
        )

    # =========================
    # RETRIEVE
    # =========================

    self._log(
        "🔎 Retrieving relevant documents..."
    )

    context, citations = (
        self.rag.retrieve(
            query,
            top_k=top_k
        )
    )

    if not context:

        return {
            "query": query,
            "answer":
                "I couldn't find relevant information "
                "in the knowledge base.",
            "citations": [],
            "retrieved_chunks": 0
        }

    self._log(
        f"📚 Retrieved "
        f"{len(citations)} chunks"
    )

    # =========================
    # PROMPT
    # =========================

    prompt = f"""
You are Alex, an AI research assistant.

Answer the user's question using ONLY
the information provided in the context.

If the answer cannot be found in the context,
say that the information is not available
in the knowledge base.

User Question:
{query}

Context:
{context}

Instructions:
- Use only the provided context.
- Do not invent facts.
- Be clear and concise.
- Mention the relevant source documents.
"""

    # =========================
    # GENERATE
    # =========================

    self._log(
        "🧠 Generating answer..."
    )

    answer = self._call_gemini(
    prompt,
    temperature=0.3
)

    if answer is None:

        return {
            "query": query,
            "answer": (
                "Gemini API quota is currently exhausted. "
                "However, the RAG retrieval pipeline worked successfully."
            ),
            "citations": citations,
            "retrieved_chunks": len(citations),
            "generation_status": "quota_exhausted"
        }

    self._log(
        "✅ Answer generated"
    )

AlexAgent.answer_with_rag = answer_with_rag
