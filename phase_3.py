# ==================== DOCUMENT PROCESSOR ====================

class DocumentProcessor:

    @staticmethod
    def chunk_text(
        text: str,
        chunk_size: int = 500,
        overlap: int = 100
    ) -> List[str]:

        sentences = re.split(
            r'(?<=[.!?])\s+',
            text.strip()
        )

        chunks = []

        current_chunk = []
        current_size = 0

        for sentence in sentences:

            sentence_len = len(sentence.split())

            if (
                current_size + sentence_len > chunk_size
                and current_chunk
            ):

                chunks.append(
                    " ".join(current_chunk)
                )

                # Approximate overlap
                overlap_count = max(
                    1,
                    overlap // 20
                )

                current_chunk = (
                    current_chunk[-overlap_count:]
                    + [sentence]
                )

                current_size = sum(
                    len(s.split())
                    for s in current_chunk
                )

            else:

                current_chunk.append(sentence)
                current_size += sentence_len

        if current_chunk:

            chunks.append(
                " ".join(current_chunk)
            )

        return chunks

# ==================== EMBEDDING GENERATOR ====================

class EmbeddingGenerator:

    def __init__(
        self,
        use_gemini: bool = False,
        api_key: Optional[str] = None
    ):

        self.use_gemini = use_gemini
        self.api_key = api_key

        self._embedding_cache = {}

        if use_gemini and api_key:

            self.client = genai.Client(
                api_key=api_key
            )

        else:

            self.client = None

    def generate_embedding(
        self,
        text: str
    ) -> List[float]:

        text_hash = hashlib.md5(
            text.encode()
        ).hexdigest()

        if text_hash in self._embedding_cache:

            return self._embedding_cache[text_hash]

        if self.use_gemini and self.client:

            try:

                response = self.client.models.embed_content(
                    model="models/embedding-001",
                    content=text
                )

                embedding = response["embedding"]

            except Exception:

                embedding = self._simple_embedding(text)

        else:

            embedding = self._simple_embedding(text)

        self._embedding_cache[text_hash] = embedding

        return embedding

    @staticmethod
    def _simple_embedding(
        text: str,
        dim: int = 384
    ) -> List[float]:

        text_hash = hashlib.md5(
            text.encode()
        ).hexdigest()

        seed = int(text_hash, 16)

        np.random.seed(
            seed % (2**31)
        )

        embedding = np.random.randn(
            dim
        ).astype(float)

        norm = np.linalg.norm(
            embedding
        )

        embedding = embedding / norm

        return embedding.tolist()

    def embed_chunks(
        self,
        chunks: List[DocumentChunk]
    ) -> List[DocumentChunk]:

        for i, chunk in enumerate(chunks):

            embedding = self.generate_embedding(
                chunk.content
            )

            chunk.embedding = embedding

            if (i + 1) % 10 == 0:

                print(
                    f"  📊 Embedded "
                    f"{i + 1}/{len(chunks)}"
                )

        return chunks

# ==================== VECTOR STORE ====================

class VectorStore:

    def __init__(self):

        self.chunks: Dict[
            str, DocumentChunk
        ] = {}

        self.documents: Dict[
            str, Document
        ] = {}

    def add_document(
        self,
        document: Document
    ):

        self.documents[
            document.id
        ] = document

        for chunk in document.chunks:

            if chunk.embedding is not None:

                self.chunks[
                    chunk.id
                ] = chunk

    def search(
        self,
        query_embedding: List[float],
        top_k: int = 5
    ) -> List[RetrievalResult]:

        if not self.chunks:
            return []

        scores = []

        query_vec = np.array(
            query_embedding
        )

        query_norm = np.linalg.norm(
            query_vec
        )

        for chunk_id, chunk in self.chunks.items():

            if chunk.embedding is None:
                continue

            chunk_vec = np.array(
                chunk.embedding
            )

            chunk_norm = np.linalg.norm(
                chunk_vec
            )

            similarity = (
                np.dot(
                    query_vec,
                    chunk_vec
                )
                /
                (
                    query_norm * chunk_norm
                    + 1e-8
                )
            )

            scores.append(
                (
                    chunk_id,
                    similarity,
                    chunk
                )
            )

        scores.sort(
            key=lambda x: x[1],
            reverse=True
        )

        results = []

        for rank, (
            chunk_id,
            similarity,
            chunk
        ) in enumerate(
            scores[:top_k],
            start=1
        ):

            doc = self.documents[
                chunk.document_id
            ]

            results.append(
                RetrievalResult(
                    chunk=chunk,
                    similarity_score=float(
                        similarity
                    ),
                    document_name=doc.name,
                    rank=rank
                )
            )

        return results

    def get_stats(self) -> Dict:

        return {
            "total_documents":
                len(self.documents),

            "total_chunks":
                len(self.chunks),

            "documents": [
                {
                    "name": doc.name,
                    "chunks": len(doc.chunks),
                    "source": doc.source
                }
                for doc in self.documents.values()
            ]
        }

# ==================== RAG RETRIEVER ====================

class RAGRetriever:

    def __init__(
        self,
        embedding_generator: EmbeddingGenerator,
        vector_store: VectorStore
    ):

        self.embeddings = embedding_generator
        self.store = vector_store

        self.retrieval_history = []

    def retrieve(
        self,
        query: str,
        top_k: int = 5
    ) -> List[RetrievalResult]:

        query_embedding = (
            self.embeddings.generate_embedding(
                query
            )
        )

        results = self.store.search(
            query_embedding,
            top_k=top_k
        )

        self.retrieval_history.append({
            "query": query,
            "results": len(results),
            "timestamp":
                datetime.now().isoformat()
        })

        return results

    def format_context(
        self,
        results: List[RetrievalResult]
    ) -> Tuple[str, List[Dict]]:

        context_parts = []
        citations = []

        for result in results:

            context_parts.append(
                f"[Source: {result.document_name}]\n"
                f"{result.chunk.content}"
            )

            citations.append({
                "source":
                    result.document_name,

                "similarity":
                    result.similarity_score,

                "rank":
                    result.rank
            })

        context = "\n\n---\n\n".join(
            context_parts
        )

        return context, citations

# ==================== RAG SYSTEM ====================

class RAGSystem:

    def __init__(
        self,
        use_gemini: bool = False,
        api_key: Optional[str] = None
    ):

        self.processor = DocumentProcessor()

        self.embeddings = EmbeddingGenerator(
            use_gemini=use_gemini,
            api_key=api_key
        )

        self.store = VectorStore()

        self.retriever = RAGRetriever(
            self.embeddings,
            self.store
        )

        print("✅ RAG System initialized")

    def ingest_text(
        self,
        text: str,
        name: str = "document",
        chunk_size: int = 500
    ):

        print(f"\n📥 Ingesting: {name}")

        doc_id = hashlib.md5(
            name.encode()
        ).hexdigest()[:8]

        document = Document(
            id=doc_id,
            name=name,
            content=text,
            source=f"text:{name}"
        )

        chunks_text = (
            self.processor.chunk_text(
                text,
                chunk_size=chunk_size
            )
        )

        for i, chunk_text in enumerate(
            chunks_text
        ):

            chunk = DocumentChunk(
                id=f"{doc_id}_chunk_{i}",
                document_id=doc_id,
                content=chunk_text,
                chunk_index=i
            )

            document.chunks.append(
                chunk
            )

        print(
            f"  ✅ {len(document.chunks)} chunks"
        )

        print(
            "  🧮 Generating embeddings..."
        )

        document.chunks = (
            self.embeddings.embed_chunks(
                document.chunks
            )
        )

        self.store.add_document(
            document
        )

        print("  ✅ Stored")

    def retrieve(
        self,
        query: str,
        top_k: int = 5
    ) -> Tuple[str, List[Dict]]:

        results = (
            self.retriever.retrieve(
                query,
                top_k=top_k
            )
        )

        context, citations = (
            self.retriever.format_context(
                results
            )
        )

        return context, citations

    def get_status(self) -> Dict:

        stats = self.store.get_stats()

        return {
            "documents":
                stats["total_documents"],

            "chunks":
                stats["total_chunks"],

            "queries":
                len(
                    self.retriever
                    .retrieval_history
                )
        }

