# ==================== DATA STRUCTURES ====================

class AgentRole(Enum):
    SUPERVISOR = "supervisor"
    RESEARCHER = "researcher"
    ANALYST = "analyst"
    STRATEGIST = "strategist"
    REVIEWER = "reviewer"


@dataclass
class AgentMessage:
    sender_id: str
    receiver_id: str
    message_type: str
    content: str
    data: Dict[str, Any] = field(default_factory=dict)
    timestamp: str = None

    def __post_init__(self):
        if self.timestamp is None:
            self.timestamp = datetime.now().isoformat()


@dataclass
class AgentMemory:
    agent_id: str
    role: AgentRole
    findings: List[Dict] = field(default_factory=list)
    conversation: List[AgentMessage] = field(default_factory=list)
    accuracy_score: float = 0.0

    def add_finding(self, finding: str, confidence: float = 0.8):
        self.findings.append({
            "finding": finding,
            "confidence": confidence,
            "timestamp": datetime.now().isoformat()
        })

    def add_message(self, message: AgentMessage):
        self.conversation.append(message)

    def get_summary(self) -> Dict:
        return {
            "agent_id": self.agent_id,
            "role": self.role.value,
            "findings": len(self.findings),
            "messages": len(self.conversation)
        }


@dataclass
class AgentTask:
    id: str
    agent_id: str
    task_type: str
    description: str
    input_data: Dict
    status: str = "pending"
    result: Optional[str] = None
    confidence: float = 0.0

# ==================== BASE AGENT ====================

class BaseAgent:
    def __init__(self, agent_id: str, role: AgentRole, name: str):
        self.agent_id = agent_id
        self.role = role
        self.name = name
        self.memory = AgentMemory(agent_id=agent_id, role=role)
        self.tasks = {}
        self.inbox = []
        self.message_bus = None

    def send_message(self, receiver_id: str, message_type: str, content: str, data: Dict = None):
        message = AgentMessage(
            sender_id=self.agent_id,
            receiver_id=receiver_id,
            message_type=message_type,
            content=content,
            data=data or {}
        )

        if self.message_bus:
            self.message_bus.deliver_message(message)

        self.memory.add_message(message)

    def receive_message(self, message: AgentMessage):
        self.inbox.append(message)
        self.memory.add_message(message)

    def execute_task(self, task: AgentTask) -> str:
        return "Task executed"

    def get_status(self) -> Dict:
        return {
            "id": self.agent_id,
            "name": self.name,
            "role": self.role.value,
            "tasks": len(self.tasks),
            "messages": len(self.inbox)
        }

