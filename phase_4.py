# ==================== MESSAGE BUS ====================

class MessageBus:
    def __init__(self):
        self.message_log = []
        self.agents = {}

    def register_agent(self, agent: BaseAgent):
        self.agents[agent.agent_id] = agent
        agent.message_bus = self

    def deliver_message(self, message: AgentMessage):
        self.message_log.append(message)
        if message.receiver_id in self.agents:
            self.agents[message.receiver_id].receive_message(message)

# ==================== MULTI-AGENT SYSTEM ====================

class MultiAgentSystem:
    def __init__(self):
        self.message_bus = MessageBus()

        self.supervisor = SupervisorAgent("supervisor")
        self.researcher = ResearcherAgent("researcher")
        self.analyst = AnalystAgent("analyst")
        self.strategist = StrategyAgent("strategist")
        self.reviewer = ReviewerAgent("reviewer")

        for agent in [self.supervisor, self.researcher, self.analyst, self.strategist, self.reviewer]:
            self.message_bus.register_agent(agent)

        self.agents = {
            "supervisor": self.supervisor,
            "researcher": self.researcher,
            "analyst": self.analyst,
            "strategist": self.strategist,
            "reviewer": self.reviewer
        }

        print("✅ Multi-Agent System initialized\n")

    def execute_goal(self, goal: str) -> Dict:
        print(f"{'='*60}")
        print(f"🎯 MULTI-AGENT EXECUTION")
        print(f"{'='*60}\n")

        print("📋 Supervisor creating workflow...")
        tasks = self.supervisor.create_workflow(goal)

        results = {}

        print("\n⚙️ Executing agents:\n")

        print("🔍 [1/5] Research Agent executing...")
        research_result = self.researcher.execute_task(tasks["research"])
        results["research"] = research_result[:200]
        print("   ✅ Complete\n")

        print("📊 [2/5] Analysis Agent executing...")
        analysis_result = self.analyst.execute_task(tasks["analysis"])
        results["analysis"] = analysis_result[:200]
        print("   ✅ Complete\n")

        print("🧠 [3/5] Strategy Agent executing...")
        strategy_result = self.strategist.execute_task(tasks["strategy"])
        results["strategy"] = strategy_result[:200]
        print("   ✅ Complete\n")

        print("✓ [4/5] Review Agent executing...")
        review_result = self.reviewer.execute_task(tasks["review"])
        results["review"] = review_result[:200]
        print("   ✅ Complete\n")

        print("🎯 [5/5] Supervisor aggregating...")
        self.supervisor.workflow_state = "completed"
        print("   ✅ Workflow complete\n")

        return {
            "goal": goal,
            "results": results,
            "agent_status": {
                agent_id: agent.get_status()
                for agent_id, agent in self.agents.items()
            },
            "total_messages": len(self.message_bus.message_log),
            "workflow_state": "completed"
        }

    def get_system_status(self) -> Dict:
        return {
            "agents": {
                agent_id: agent.get_status()
                for agent_id, agent in self.agents.items()
            },
            "total_messages": len(self.message_bus.message_log),
            "system_state": "operational"
        }

